-- 迁移 0017：删除 pgvector 的 rag_chunks 表（向量层迁移至 Qdrant）
--
-- 背景：向量存储从 @langchain/pgvector（PG rag_chunks 表）整体迁移到 Qdrant：
-- - 切片向量、正文（content）与业务元数据（wikiId/documentId 等）改存 Qdrant point 的
--   命名向量 + payload（见 apps/server/src/modules/rag/rag.store.ts）
-- - 切片内容指纹与索引状态仍记录在 rag_sync 表（本迁移不动）
--
-- 迁移后重建索引的操作（与旧约定一致，靠 worker 启动自愈）：
--   UPDATE rag_sync SET content_hash = NULL, status = 'pending', error = NULL;
--   重启 server 后 recoverStaleTasks 自动把 pending 全部重新入队，Qdrant 侧重建向量
DROP TABLE IF EXISTS "rag_chunks";
-- pgvector 扩展：全新环境（官方 postgres 镜像，历史迁移已剥离 pgvector 依赖）本就不存在；
